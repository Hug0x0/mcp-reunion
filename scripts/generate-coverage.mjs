#!/usr/bin/env node

import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const MODULES_DIR = path.join(ROOT, 'src', 'modules');
const OUT_FILE = path.join(ROOT, 'COVERAGE.md');

const SOURCE_LABELS = new Map([
  ['catalog', 'data.regionreunion.com catalog'],
  ['national-elections', 'tabular-api.data.gouv.fr'],
]);

function titleCaseModule(fileName) {
  return fileName
    .replace(/\.ts$/, '')
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

function extractStringConstants(source) {
  const constants = new Map();
  const pattern = /const\s+(DATASET_[A-Z0-9_]+)\s*=\s*'([^']+)'/g;
  for (const match of source.matchAll(pattern)) {
    constants.set(match[1], match[2]);
  }
  return constants;
}

function extractRecordMapValues(source) {
  const values = [];
  const mapPattern = /const\s+[A-Z0-9_]+\s*:\s*Record<string,\s*string>\s*=\s*\{([\s\S]*?)\};/g;
  for (const mapMatch of source.matchAll(mapPattern)) {
    const body = mapMatch[1];
    for (const valueMatch of body.matchAll(/:\s*(DATASET_[A-Z0-9_]+)/g)) {
      values.push(valueMatch[1]);
    }
  }
  return values;
}

function extractTools(source) {
  return [...source.matchAll(/server\.tool\(\s*\n\s*'([^']+)'/g)].map((match) => match[1]);
}

async function main() {
  const files = (await readdir(MODULES_DIR))
    .filter((file) => file.endsWith('.ts') && file !== 'index.ts')
    .sort();

  const rows = [];
  let totalTools = 0;
  let totalDatasets = 0;

  for (const file of files) {
    const source = await readFile(path.join(MODULES_DIR, file), 'utf8');
    const moduleKey = file.replace(/\.ts$/, '');
    const constants = extractStringConstants(source);
    const mappedDatasetRefs = extractRecordMapValues(source);
    const datasets = [...new Set([...constants.values(), ...mappedDatasetRefs.map((key) => constants.get(key))].filter(Boolean))].sort();
    const tools = extractTools(source).sort();

    totalTools += tools.length;
    totalDatasets += datasets.length;

    rows.push({
      module: titleCaseModule(file),
      source: SOURCE_LABELS.get(moduleKey) ?? 'data.regionreunion.com',
      datasets,
      tools,
    });
  }

  const lines = [
    '# Dataset Coverage',
    '',
    '<!-- Generated by `npm run docs:coverage`. Do not edit by hand. -->',
    '',
    `Total modules: ${rows.length}`,
    `Total dedicated tools: ${totalTools}`,
    `Total referenced datasets/resources: ${totalDatasets}`,
    '',
    '| Module | Source | Datasets/resources | Tools |',
    '| --- | --- | --- | --- |',
  ];

  for (const row of rows) {
    lines.push(
      `| ${row.module} | ${row.source} | ${row.datasets.map((dataset) => `\`${dataset}\``).join('<br>') || '-'} | ${row.tools.map((tool) => `\`${tool}\``).join('<br>') || '-'} |`
    );
  }

  lines.push('');
  await writeFile(OUT_FILE, `${lines.join('\n')}\n`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});

